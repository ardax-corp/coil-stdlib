#!/usr/bin/env python3
"""Regenerate the reference tables in tests/math.hy.

Expected values come from CPython's `math` (the platform libm) except
`cbrt`, whose reference is the correctly rounded cube root computed with
`decimal` (glibc's cbrt is not correctly rounded: cbrt(27) is
3.0000000000000004 there). Run from the repository root:

    python3 scripts/gen_math_cases.py && coil-fmt tests/math.hy

It rewrites the block between the `BEGIN GENERATED` / `END GENERATED`
markers in tests/math.hy and leaves the rest of the file alone.
"""

import math
import random
from decimal import Decimal, getcontext
from pathlib import Path

TEST = Path(__file__).resolve().parent.parent / "tests" / "math.hy"
BEGIN = "// BEGIN GENERATED by scripts/gen_math_cases.py; do not edit by hand.\n"
END = "// END GENERATED\n"
SAMPLES = 48


def lit(x: float) -> str:
    """A Coil float expression that evaluates to exactly `x`."""
    if math.isnan(x):
        return "NAN"
    if math.isinf(x):
        return "INF" if x > 0 else "-INF"
    if x == 0.0:
        return "-0.0" if math.copysign(1.0, x) < 0 else "0.0"
    ax = abs(x)
    if 1e-12 <= ax < 1e16:
        s = repr(x)
        if "e" in s or "E" in s:
            s = format(Decimal(s), "f")
        if "." not in s:
            s += ".0"
        assert float(s) == x
        return s
    f, e = math.frexp(x)
    m = f * 2.0
    e -= 1
    s = repr(m)
    assert "e" not in s and float(s) * 2.0**e == x
    return f"{s} * (2.0 ** {e}.0)" if e >= 0 else f"{s} * (2.0 ** -{-e}.0)"


def cbrt_ref(x: float) -> float:
    if x == 0.0 or math.isinf(x) or math.isnan(x):
        return x
    getcontext().prec = 60
    d = Decimal(abs(x))
    r = d ** (Decimal(1) / Decimal(3))
    # Two Newton steps at 60 digits settle the last digits of the root.
    for _ in range(2):
        r = (2 * r + d / (r * r)) / 3
    y = float(r)
    return -y if x < 0 else y


def value(rng: random.Random, i: int) -> float:
    u = rng.random()
    s = -1.0 if rng.random() < 0.5 else 1.0
    mode = i % 3
    if mode == 0:
        return s * u * 10.0
    if mode == 1:
        return s * u * 1000.0
    return s * (1.0 + u) * 2.0 ** rng.randint(-60, 60)


def unit(rng: random.Random) -> float:
    return (rng.random() * 2.0) - 1.0


def expected(name: str, x: float) -> float:
    """`name(x)` with IEEE results where CPython raises instead."""
    try:
        return libm(name)(x)
    except OverflowError:
        return math.copysign(math.inf, x) if name == "sinh" else math.inf
    except ValueError:
        if name in ("ln", "log2", "log10") and x == 0.0:
            return -math.inf
        return math.nan


def floor_ref(x: float) -> float:
    if x == 0.0 or not math.isfinite(x):
        return x
    return float(math.floor(x))


def ceil_ref(x: float) -> float:
    if x == 0.0 or not math.isfinite(x):
        return x
    r = float(math.ceil(x))
    return -0.0 if r == 0.0 and x < 0.0 else r


def libm(name):
    refs = {"ln": math.log, "cbrt": cbrt_ref, "floor": floor_ref, "ceil": ceil_ref}
    return refs.get(name) or getattr(math, name)


UNARY = [
    # name, input generator, inputs that pin a range edge
    ("sin", value, [1647099.0, 1647100.0, 12345678.9, 1e10, 2.0**100, 2.0**1000, -(2.0**600), 0.5, -0.5]),
    ("cos", value, [1647099.0, 1647100.0, 12345678.9, 1e10, 2.0**100, 2.0**1000, -(2.0**600), 0.5]),
    ("tan", value, [1647100.0, 1e10, 2.0**100, -(2.0**600), 1.0, 1.5]),
    ("sqrt", lambda r, i: abs(value(r, i)), [2.0, 0.5, 5e-324, 2.0**-1022, 2.0**1023, 1e300]),
    ("floor", value, [-0.5, 0.5, -1.5, 2.0**52 + 0.5, -(2.0**52) - 0.5, 4503599627370495.5]),
    ("ceil", value, [-0.5, 0.5, -1.5, 2.0**52 + 0.5, -(2.0**52) - 0.5, -4503599627370495.5]),
    ("exp", lambda r, i: value(r, i) / 20.0 * 7.0, [1.0, -1.0, 700.5, 709.7, -708.5, -720.25, -744.5]),
    ("ln", lambda r, i: abs(value(r, i)), [5e-324, 2.0**-1022, 2.0**1023, 1.0000001, 0.9999999]),
    ("log2", lambda r, i: abs(value(r, i)), [5e-324, 3.0, 2.0**1023 * 1.5, 0.75]),
    ("log10", lambda r, i: abs(value(r, i)), [5e-324, 2.0, 1e300, 0.3]),
    ("atan", value, [2.0**66, -(2.0**70), 0.4375, 1.1875, 2.4375, 1e-10]),
    ("asin", lambda r, i: unit(r), [0.5, -0.5, 0.975, -0.99, 1e-9]),
    ("acos", lambda r, i: unit(r), [0.5, -0.5, 0.975, -0.99, 1e-18]),
    ("cbrt", value, [3.375, -0.001, 5e-324, 2.0**-1022, 2.0**1023, 1e300]),
    ("sinh", value, [1.0, -1.0, 0.25, 709.0, -709.5, 1e-9]),
    ("cosh", value, [1.0, -1.0, 0.25, 709.0, -709.5, 1e-9]),
    ("tanh", value, [0.25, 0.5, -0.6, 19.0, -21.0, 1e-9]),
]


# IEEE edge inputs every unary function is checked on.
SPECIALS = [0.0, -0.0, math.inf, -math.inf, math.nan, 5e-324, -5e-324, 2.0**-1022, 2.0**1023, 710.0, -750.0]


def table(name: str, values: list) -> str:
    # One element per line, as coil-fmt lays out a long array literal.
    rows = [f"        {v}," for v in values]
    return f"fn {name}() -> Vec<float> {{\n    return [\n" + "\n".join(rows) + "\n    ];\n}\n\n"


def main() -> None:
    rng = random.Random(20261028)
    out = [BEGIN, "// Pairs of input and expected result; `atan2` rows are (y, x, expected).\n"]
    for name, gen, edges in UNARY:
        xs = [gen(rng, i) for i in range(SAMPLES)] + edges + SPECIALS
        cells = []
        for x in xs:
            cells += [lit(x), lit(expected(name, x))]
        out.append(table(name + "_cases", cells))
    cells = []
    for i in range(SAMPLES):
        y, x = value(rng, i), value(rng, i)
        cells += [lit(y), lit(x), lit(math.atan2(y, x))]
    for y, x in [(1.0, 2.0**70), (-(2.0**70), 1.0), (1e-30, -1.0), (-1e-30, -1.0)]:
        cells += [lit(y), lit(x), lit(math.atan2(y, x))]
    grid = [0.0, -0.0, 1.0, -1.0, math.inf, -math.inf, math.nan, 2.0, -3.0]
    for y in grid:
        for x in grid:
            cells += [lit(y), lit(x), lit(math.atan2(y, x))]
    out.append(table("atan2_cases", cells))
    out.append(END)
    text = TEST.read_text()
    start = text.index(BEGIN)
    stop = text.index(END) + len(END)
    TEST.write_text(text[:start] + "".join(out) + text[stop:])


if __name__ == "__main__":
    main()
